# Operações de fatiamento sobre a lista dada

lista = [10, 2, 32, 14, 35, 46, 17, 58, 199, 19]

print('1. Elementos de índices pares:', lista[::2])
print('2. Elementos de índices ímpares:', lista[1::2])
print('3. Elementos entre índices 2 (inclusive) e 4 (exclusive):', lista[2:4])
print('4. Elemento de índice 1, depois distantes 3 posições:', lista[1::3])
